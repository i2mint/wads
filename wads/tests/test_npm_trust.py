"""``wads npm-trust`` (i2mint/wads#104): discovery of npm publishers, the plan, the apply.

Discovery runs over real layouts: the three wads frontend profiles (generated by
``apply_frontend``), a changesets monorepo that publishes through a ``release`` script,
and a pnpm monorepo with a custom ``pnpm -r publish`` job and an ``environment``. npm
itself is a fake ``run`` callable, so nothing here touches a network.
"""

import json
import subprocess

import pytest

from wads.npm_trust import (
    Publisher,
    apply_trust,
    discover,
    github_slug,
    run_npm_trust,
    render_rows,
    survey,
    trust_command,
)
from wads.profiles import apply_frontend

SLUG = "o/r"


def _write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text if isinstance(text, str) else json.dumps(text))


def _workflow(repo, name, *steps, environment=None, extra_job=None):
    job = {"runs-on": "ubuntu-latest", "steps": list(steps), **(extra_job or {})}
    if environment:
        job["environment"] = environment
    import yaml

    _write(
        repo / ".github" / "workflows" / name,
        yaml.safe_dump({"on": "push", "jobs": {"j": job}}),
    )


def _names(repo):
    return [(p.package, p.workflow, p.environment) for p in discover(repo, repo=SLUG)]


@pytest.mark.parametrize(
    "profile, workflow",
    [("js", "npm-ci.yml"), ("ts", "npm-ci-ts.yml"), ("ts-monorepo", "npm-ci-ts.yml")],
)
def test_the_wads_frontend_stubs_are_found_by_their_caller_filename(
    tmp_path, profile, workflow
):
    apply_frontend(str(tmp_path), profile=profile, project_name="demo")
    assert _names(tmp_path) == [("demo", workflow, "")]


def test_a_pnpm_monorepo_with_a_custom_publish_job_lists_public_packages_and_the_environment(
    tmp_path,
):
    _write(tmp_path / "package.json", {"name": "root", "private": True})
    _write(
        tmp_path / "pnpm-workspace.yaml",
        "packages:\n  - 'packages/*'\n  - '!packages/skip'\n",
    )
    for name, private in [
        ("a", False),
        ("b", False),
        ("skip", False),
        ("hidden", True),
    ]:
        _write(
            tmp_path / "packages" / name / "package.json",
            {"name": f"@x/{name}", "private": private},
        )
    _workflow(
        tmp_path,
        "ci.yml",
        {"run": "pnpm -r publish --access public"},
        environment={"name": "npm"},
    )
    assert _names(tmp_path) == [("@x/a", "ci.yml", "npm"), ("@x/b", "ci.yml", "npm")]


def test_a_changesets_repo_publishing_through_a_release_script(tmp_path):
    _write(
        tmp_path / "package.json",
        {
            "name": "mono",
            "private": True,
            "workspaces": ["packages/*"],
            "scripts": {"release": "changeset publish"},
        },
    )
    _write(tmp_path / "packages" / "core" / "package.json", {"name": "core"})
    _workflow(
        tmp_path,
        "release.yml",
        {"uses": "changesets/action@v1", "with": {"publish": "pnpm release"}},
    )
    assert _names(tmp_path) == [("core", "release.yml", "")]


def test_a_script_that_does_not_publish_is_not_a_publisher(tmp_path):
    _write(
        tmp_path / "package.json",
        {"name": "x", "scripts": {"build": "tsup", "test": "vitest"}},
    )
    _workflow(tmp_path, "ci.yml", {"run": "pnpm build"}, {"run": "pnpm test"})
    assert discover(tmp_path, repo=SLUG) == []


def test_working_directory_scopes_the_packages(tmp_path):
    _write(tmp_path / "package.json", {"name": "root"})
    _write(tmp_path / "sub" / "package.json", {"name": "sub"})
    _workflow(tmp_path, "pub.yml", {"run": "npm publish", "working-directory": "sub"})
    assert _names(tmp_path) == [("sub", "pub.yml", "")]


def test_github_slug_reads_ssh_and_https_remotes():
    def remote(url):
        return lambda argv: subprocess.CompletedProcess(argv, 0, url + "\n", "")

    assert (
        github_slug(".", run=remote("git@github.com:i2mint/wads.git")) == "i2mint/wads"
    )
    assert (
        github_slug(".", run=remote("https://github.com/thorwhalen/ge"))
        == "thorwhalen/ge"
    )
    assert github_slug(".", run=remote("git@gitlab.com:a/b.git")) is None


class FakeNpm:
    """``run`` stand-in: which packages exist, who is trusted, which attaches fail."""

    def __init__(self, on_npm=(), trusted=(), failing=(), logged_in=True):
        self.on_npm, self.trusted, self.failing, self.logged_in = (
            set(on_npm),
            set(trusted),
            set(failing),
            logged_in,
        )
        self.attached, self.calls = [], []

    def __call__(self, argv):
        argv = list(argv)
        self.calls.append(argv)
        done = lambda rc=0, out="", err="": subprocess.CompletedProcess(
            argv, rc, out, err
        )
        if argv[:2] == ["npm", "view"]:
            return (
                done() if argv[2] in self.on_npm else done(1, err="npm error code E404")
            )
        if argv[:3] == ["npm", "trust", "list"]:
            listed = argv[3] in self.trusted or argv[3] in self.attached
            return done(out=f"github {SLUG} release.yml\n" if listed else "")
        if argv[:3] == ["npm", "trust", "github"]:
            if argv[3] in self.failing:
                return done(1, err="npm error EOTP")
            self.attached.append(argv[3])
            return done()
        if argv[:2] == ["npm", "whoami"]:
            return done(0 if self.logged_in else 1)
        return done(127, err="unexpected")


PUBLISHERS = [Publisher(n, SLUG, "release.yml") for n in ("new", "have", "ok", "bad")]


def test_survey_tells_published_trusted_and_first_publish_needed():
    npm = FakeNpm(on_npm={"have", "ok", "bad"}, trusted={"have"})
    rows = {r.publisher.package: r.status for r in survey(PUBLISHERS, run=npm)}
    assert rows == {
        "new": "first-publish-needed",
        "have": "trusted",
        "ok": "on-npm",
        "bad": "on-npm",
    }


def test_survey_offline_asks_npm_nothing():
    npm = FakeNpm()
    assert {r.status for r in survey(PUBLISHERS, run=npm, check_npm=False)} == {
        "unknown"
    }
    assert npm.calls == []


def test_apply_skips_unpublished_continues_past_failures_and_verifies():
    npm = FakeNpm(on_npm={"have", "ok", "bad"}, trusted={"have"}, failing={"bad"})
    outcomes = {
        o.row.publisher.package: o
        for o in apply_trust(survey(PUBLISHERS, run=npm), run=npm)
    }
    assert {k: o.action for k, o in outcomes.items()} == {
        "new": "skipped",
        "have": "already-trusted",
        "ok": "attached",
        "bad": "failed",
    }
    assert outcomes["ok"].verified is True
    assert "EOTP" in outcomes["bad"].detail
    assert npm.attached == ["ok"]


def test_trust_command_includes_the_environment_only_when_there_is_one():
    plain = trust_command(Publisher("p", SLUG, "w.yml"))
    assert "--env" not in plain and plain[-2:] == ["--allow-publish", "-y"]
    assert trust_command(Publisher("p", SLUG, "w.yml", "npm"))[-4:-2] == [
        "--env",
        "npm",
    ]


def test_render_rows_formats():
    rows = survey([Publisher("p", SLUG, "w.yml", "npm")], check_npm=False)
    assert render_rows(rows, "tsv").splitlines()[1] == "p\to/r\tw.yml\tnpm\tunknown"
    assert json.loads(render_rows(rows, "json"))[0]["package"] == "p"
    assert "package" in render_rows(rows)
    with pytest.raises(ValueError):
        render_rows(rows, "xml")


def test_the_command_is_a_dry_run_unless_asked_to_apply(tmp_path):
    _write(tmp_path / "package.json", {"name": "p"})
    _workflow(tmp_path, "release.yml", {"run": "npm publish"})
    npm, lines = FakeNpm(on_npm={"p"}), []
    run_npm_trust(str(tmp_path), github_repo=SLUG, run=npm, out=lines.append)
    assert any("Would run" in line for line in lines)
    assert npm.attached == []
    run_npm_trust(
        str(tmp_path), github_repo=SLUG, dry_run=True, run=npm, out=lines.append
    )
    assert npm.attached == []
    run_npm_trust(
        str(tmp_path), github_repo=SLUG, apply=True, run=npm, out=lines.append
    )
    assert npm.attached == ["p"]


def test_apply_refuses_when_not_logged_in_and_flags_contradict(tmp_path):
    _write(tmp_path / "package.json", {"name": "p"})
    _workflow(tmp_path, "release.yml", {"run": "npm publish"})
    with pytest.raises(SystemExit, match="npm login"):
        run_npm_trust(
            str(tmp_path),
            github_repo=SLUG,
            apply=True,
            run=FakeNpm(on_npm={"p"}, logged_in=False),
            out=lambda _: None,
        )
    with pytest.raises(SystemExit, match="contradict"):
        run_npm_trust(str(tmp_path), apply=True, dry_run=True)


def test_apply_exits_nonzero_when_an_attach_fails(tmp_path):
    _write(tmp_path / "package.json", {"name": "p"})
    _workflow(tmp_path, "release.yml", {"run": "npm publish"})
    with pytest.raises(SystemExit) as exc:
        run_npm_trust(
            str(tmp_path),
            github_repo=SLUG,
            apply=True,
            run=FakeNpm(on_npm={"p"}, failing={"p"}),
            out=lambda _: None,
        )
    assert exc.value.code == 1
